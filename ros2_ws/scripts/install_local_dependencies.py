#!/usr/bin/env python3
"""Extract missing Debian dependencies into .deps/root without changing the OS.

Uses the host's configured apt repositories and package versions. Source env.sh
afterwards. Prefer normal rosdep/apt installation on deployment machines.
"""

from pathlib import Path
import re
import shlex
import subprocess

PACKAGES = [
    "ros-jazzy-controller-manager", "ros-jazzy-joint-state-broadcaster",
    "ros-jazzy-joint-trajectory-controller", "ros-jazzy-diff-drive-controller",
    "ros-jazzy-xacro", "ros-jazzy-urdfdom-py",
    "ros-jazzy-foxglove-bridge", "ros-jazzy-launch-xml",
]


def relocate(root):
    prefix = root / "opt/ros/jazzy"
    # Some binary packages embed absolute include paths in exported CMake targets.
    # Rewrite only paths actually supplied by this local prefix; system ROS
    # dependencies continue to resolve to their installed /opt/ros paths.
    for path in prefix.rglob("*.cmake"):
        def local_path(match):
            candidate = root / match.group(0).lstrip("/")
            return str(candidate) if candidate.exists() else match.group(0)
        path.write_text(re.sub(r"(?<![A-Za-z0-9_/])/opt/ros/jazzy/[A-Za-z0-9_./+-]+", local_path, path.read_text()))
    exports = {
        "AMENT_PREFIX_PATH": str(prefix), "CMAKE_PREFIX_PATH": str(prefix),
        "LD_LIBRARY_PATH": f"{prefix}/lib:{root}/usr/lib/x86_64-linux-gnu",
        "LIBRARY_PATH": f"{prefix}/lib:{root}/usr/lib/x86_64-linux-gnu",
        "PYTHONPATH": f"{prefix}/lib/python3.12/site-packages:{root}/usr/lib/python3/dist-packages",
        "PATH": f"{prefix}/bin",
    }
    content = "# Generated by install_local_dependencies.py\n" + "".join(
        f'export {name}={shlex.quote(value)}${{{name}:+:${name}}}\n'
        for name, value in exports.items())
    for extension in ("sh", "bash"):
        (prefix / f"local_setup.{extension}").write_text(content)


def main():
    directory = Path(__file__).resolve().parents[1] / ".deps"
    downloads = directory / "debs"
    root = directory / "root"
    downloads.mkdir(parents=True, exist_ok=True)
    root.mkdir(exist_ok=True)
    (directory / "COLCON_IGNORE").touch()
    lists = directory / "apt/lists"
    (lists / "partial").mkdir(parents=True, exist_ok=True)
    options = ["-o", f"Dir::State::lists={lists}", "-o", "Debug::NoLocking=1"]
    subprocess.run(["apt-get", *options, "update"], check=True)
    plan = subprocess.check_output(["apt-get", *options, "-s", "install", *PACKAGES], text=True)
    packages = [line.split()[1] for line in plan.splitlines() if line.startswith("Inst ")]
    if packages:
        subprocess.run(["apt", *options, "download", *packages], cwd=downloads, check=True)
        for archive in sorted(downloads.glob("*.deb")):
            subprocess.run(["dpkg-deb", "-x", str(archive), str(root)], check=True)
        relocate(root)
    (directory / "packages.txt").write_text(plan)
    print(f"Dependencies extracted to {root}. Source scripts/env.sh before building.")


if __name__ == "__main__":
    main()
